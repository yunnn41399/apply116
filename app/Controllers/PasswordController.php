<?php

namespace App\Controllers;

use App\Controllers\BaseController;
use App\Models\CandidateModel;
use CodeIgniter\HTTP\ResponseInterface;

class PasswordController extends BaseController
{
    /**
     * 顯示忘記密碼頁面
     */
    public function forgot()
    {
        /*
        |--------------------------------------------------------------------------
        | 產生 4 位數英數驗證碼
        |--------------------------------------------------------------------------
        |
        | 與 LoginController 使用完全相同的驗證碼規則
        |
        */

        $captcha = strtoupper(
            substr(
                str_shuffle('ABCDEFGHJKLMNPQRSTUVWXYZ23456789'),
                0,
                4
            )
        );


        /*
        |--------------------------------------------------------------------------
        | 將驗證碼存入 Session
        |--------------------------------------------------------------------------
        */

        session()->set('captcha', $captcha);


        /*
        |--------------------------------------------------------------------------
        | 顯示忘記密碼頁面
        |--------------------------------------------------------------------------
        */

        return view('Login/forgot_password', [
            'captcha' => $captcha
        ]);
    }


    /**
     * 驗證考生身分
     *
     * 驗證：
     * 1. 學測應試號碼
     * 2. 身分證號碼末四碼
     * 3. 驗證碼
     */
    public function verify()
    {
        /*
        |--------------------------------------------------------------------------
        | 取得表單資料
        |--------------------------------------------------------------------------
        */

        $examNumber = trim(
            $this->request->getPost('exam_number')
        );

        $idLastFour = trim(
            $this->request->getPost('id_last_four')
        );

        $captcha = strtoupper(
            trim(
                $this->request->getPost('captcha')
            )
        );


        $candidateModel = new CandidateModel();


        /*
        |--------------------------------------------------------------------------
        | ① 檢查學測應試號碼
        |--------------------------------------------------------------------------
        */

        if (empty($examNumber)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '請輸入學測應試號碼。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | 查詢考生
        |--------------------------------------------------------------------------
        */

        $candidate = $candidateModel
            ->where('exam_number', $examNumber)
            ->first();


        /*
        |--------------------------------------------------------------------------
        | 學測應試號碼錯誤
        |--------------------------------------------------------------------------
        |
        | 學測應試號碼錯誤：
        | → 不保留任何欄位
        |
        */

        if (!$candidate) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '學測應試號碼錯誤。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ② 檢查身分證末四碼
        |--------------------------------------------------------------------------
        */

        if (empty($idLastFour)) {

            session()->setFlashdata(
                'old_exam_number',
                $examNumber
            );

            return redirect()
                ->back()
                ->with(
                    'error',
                    '請輸入身分證號碼末四碼。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | 檢查身分證末四碼格式
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/^[0-9]{4}$/', $idLastFour)) {

            session()->setFlashdata(
                'old_exam_number',
                $examNumber
            );

            return redirect()
                ->back()
                ->with(
                    'error',
                    '身分證號碼末四碼必須為 4 位數字。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | 取得資料庫中的身分證末四碼
        |--------------------------------------------------------------------------
        */

        $lastFourDigits = substr(
            $candidate['id_number'],
            -4
        );


        /*
        |--------------------------------------------------------------------------
        | 身分證末四碼錯誤
        |--------------------------------------------------------------------------
        */

        if ($idLastFour !== $lastFourDigits) {

            session()->setFlashdata(
                'old_exam_number',
                $examNumber
            );

            return redirect()
                ->back()
                ->with(
                    'error',
                    '身分證號碼錯誤。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ③ 檢查驗證碼
        |--------------------------------------------------------------------------
        */

        if (empty($captcha)) {

            session()->setFlashdata(
                'old_exam_number',
                $examNumber
            );

            return redirect()
                ->back()
                ->with(
                    'error',
                    '請輸入驗證碼。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | 取得 Session 中的驗證碼
        |--------------------------------------------------------------------------
        */

        $sessionCaptcha = session()->get('captcha');


        /*
        |--------------------------------------------------------------------------
        | 比對驗證碼
        |--------------------------------------------------------------------------
        */

        if (
            empty($sessionCaptcha) ||
            $captcha !== strtoupper($sessionCaptcha)
        ) {

            session()->setFlashdata(
                'old_exam_number',
                $examNumber
            );

            return redirect()
                ->back()
                ->with(
                    'error',
                    '驗證碼錯誤。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ④ 身分驗證成功
        |--------------------------------------------------------------------------
        */

        session()->set([
            'password_reset_candidate_id' => $candidate['id'],
            'password_reset_verified'     => true,
        ]);


        /*
        |--------------------------------------------------------------------------
        | 驗證碼使用完畢
        |--------------------------------------------------------------------------
        */

        session()->remove('captcha');


        /*
        |--------------------------------------------------------------------------
        | 前往設定新密碼
        |--------------------------------------------------------------------------
        */

        return redirect()->to('/reset-password');
    }


    /**
     * 顯示設定新密碼頁面
     */
    public function reset()
    {
        /*
        |--------------------------------------------------------------------------
        | 確認是否已完成身分驗證
        |--------------------------------------------------------------------------
        */

        $verified = session()->get(
            'password_reset_verified'
        );

        $candidateId = session()->get(
            'password_reset_candidate_id'
        );


        if (!$verified || !$candidateId) {

            return redirect()
                ->to('/forgot-password')
                ->with(
                    'error',
                    '請先完成身分驗證。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | 顯示設定新密碼頁面
        |--------------------------------------------------------------------------
        */

        return view('Login/reset_password');
    }


    /**
     * 更新新密碼
     */
    public function update()
    {
        /*
        |--------------------------------------------------------------------------
        | ① 確認是否完成身分驗證
        |--------------------------------------------------------------------------
        */

        $verified = session()->get(
            'password_reset_verified'
        );

        $candidateId = session()->get(
            'password_reset_candidate_id'
        );


        if (!$verified || !$candidateId) {

            return redirect()
                ->to('/forgot-password')
                ->with(
                    'error',
                    '請先完成身分驗證。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ② 取得新密碼
        |--------------------------------------------------------------------------
        */

        $newPassword = $this->request->getPost(
            'password'
        );

        $passwordConfirm = $this->request->getPost(
            'password_confirm'
        );


        /*
        |--------------------------------------------------------------------------
        | ③ 檢查是否輸入新密碼
        |--------------------------------------------------------------------------
        */

        if (empty($newPassword)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '請輸入新密碼。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ④ 密碼長度
        |--------------------------------------------------------------------------
        */

        if (strlen($newPassword) < 8) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '密碼至少需要 8 個字元。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑤ 大寫英文字母
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/[A-Z]/', $newPassword)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '密碼至少需要 1 個大寫英文字母。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑥ 小寫英文字母
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/[a-z]/', $newPassword)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '密碼至少需要 1 個小寫英文字母。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑦ 數字
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/[0-9]/', $newPassword)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '密碼至少需要 1 個數字。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑧ 確認密碼
        |--------------------------------------------------------------------------
        */

        if (empty($passwordConfirm)) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '請輸入確認密碼。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑨ 確認兩次密碼是否一致
        |--------------------------------------------------------------------------
        */

        if ($newPassword !== $passwordConfirm) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '兩次輸入的密碼不一致。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑩ Candidate Model
        |--------------------------------------------------------------------------
        */

        $candidateModel = new CandidateModel();


        /*
        |--------------------------------------------------------------------------
        | ⑪ Hash 新密碼
        |--------------------------------------------------------------------------
        */

        $hashedPassword = password_hash(
            $newPassword,
            PASSWORD_DEFAULT
        );


        /*
        |--------------------------------------------------------------------------
        | ⑫ 更新資料庫
        |--------------------------------------------------------------------------
        */

        $updated = $candidateModel->update(
            $candidateId,
            [
                'password' => $hashedPassword,
            ]
        );


        /*
        |--------------------------------------------------------------------------
        | ⑬ 更新失敗
        |--------------------------------------------------------------------------
        */

        if (!$updated) {

            return redirect()
                ->back()
                ->with(
                    'error',
                    '密碼更新失敗，請稍後再試。'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | ⑭ 清除密碼重設 Session
        |--------------------------------------------------------------------------
        */

        session()->remove([
            'password_reset_candidate_id',
            'password_reset_verified',
        ]);


        /*
        |--------------------------------------------------------------------------
        | ⑮ 完成
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->to('/login')
            ->with(
                'success',
                '密碼修改成功，請使用新密碼重新登入。'
            );
    }
}